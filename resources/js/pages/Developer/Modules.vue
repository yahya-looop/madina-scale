interface ApiErrorResponse {
  message?: string;
  errors?: Record<string, string | string[]>;
}

interface ApiResponse<T> {
  data?: T;
  message?: string;
  errors?: Record<string, string | string[]>;
}

interface ModuleForm {
  name: string;
  slug: string;
  description: string;
  icon: string;
  sort_order: number;
  is_active: boolean;
}

