function moduleInitial(module: Module): string {
  const value = module.name.trim();

  return value.length > 0
    ? value.charAt(0).toUpperCase()
    : "M";
}

function formatSortOrder(value: number): string {
  return String(Math.max(0, Number(value) || 0)).padStart(2, "0");
}

function clearFilters(): void {
  searchQuery.value = "";
  statusFilter.value = "all";
}

function selectedIconName(): string {
  if (selectedIconOption.value) {
    return selectedIconOption.value.label;
  }

  return form.value.icon || "No icon selected";
}

function moduleIconLabel(module: Module): string {
  if (!module.icon) {
    return "Default icon";
  }

  const match = iconOptions.value.find(
    (icon) =>
      icon.name.toLowerCase() ===
      module.icon!.toLowerCase(),
  );

  return match?.label ?? module.icon;
}

