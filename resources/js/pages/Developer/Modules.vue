/* -------------------------------------------------------------------------- */
/* State                                                                      */
/* -------------------------------------------------------------------------- */

const modules = ref<Module[]>([]);

const isLoading = ref(false);
const isSaving = ref(false);

const showModal = ref(false);
const editingModule = ref<Module | null>(null);

const searchQuery = ref("");
const statusFilter = ref<"all" | "active" | "inactive">("all");

const operationMessage = ref("");
const operationMessageType = ref<"success" | "error">("success");

const validationErrors = ref<Record<string, string[]>>({});

const showIconPicker = ref(false);
const iconSearchQuery = ref("");

const slugWasAutoGenerated = ref(true);

const form = ref<ModuleForm>(createEmptyForm());

/* -------------------------------------------------------------------------- */
/* Lucide icon registry                                                       */
/* -------------------------------------------------------------------------- */

const lucideRegistry = LucideIcons as unknown as Record<
  string,
  unknown
>;

const ignoredLucideExports = new Set([
  "Icon",
  "icons",
  "createLucideIcon",
  "default",
  "toKebabCase",
  "toPascalCase",
  "DynamicIcon",
]);

function isIconComponentExport(name: string): boolean {
  if (ignoredLucideExports.has(name)) {
    return false;
  }

  return /^[A-Z][A-Za-z0-9]*$/.test(name);
}

function humanizeIconName(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
}

const iconOptions = computed<IconOption[]>(() => {
  return Object.entries(lucideRegistry)
    .filter(([name, component]) => {
      return (
        isIconComponentExport(name) &&
        component !== null &&
        component !== undefined
      );
    })
    .map(([name, component]) => ({
      name,
      label: humanizeIconName(name),
      component: component as Component,
    }))
    .sort((a, b) => a.label.localeCompare(b.label));
});

const filteredIconOptions = computed<IconOption[]>(() => {
  const query = iconSearchQuery.value.trim().toLowerCase();

  if (!query) {
    return iconOptions.value;
  }

  return iconOptions.value.filter((icon) => {
    return (
      icon.name.toLowerCase().includes(query) ||
      icon.label.toLowerCase().includes(query)
    );
  });
});

const selectedIconOption = computed<IconOption | null>(() => {
  const value = form.value.icon.trim();

  if (!value) {
    return null;
  }

  return (
    iconOptions.value.find(
      (icon) => icon.name.toLowerCase() === value.toLowerCase(),
    ) ?? null
  );
});

const iconPickerCountLabel = computed<string>(() => {
  if (iconSearchQuery.value.trim()) {
    return `${filteredIconOptions.value.length} icons`;
  }

  return `${iconOptions.value.length} icons`;
});

/* -------------------------------------------------------------------------- */
/* Form                                                                       */
/* -------------------------------------------------------------------------- */

function createEmptyForm(): ModuleForm {
  return {
    name: "",
    slug: "",
    description: "",
    icon: "",
    sort_order: 0,
    is_active: true,
  };
}

function openCreateModal(): void {
  editingModule.value = null;
  resetForm();

  form.value.sort_order = nextAvailableSortOrder.value;

  operationMessage.value = "";
  slugWasAutoGenerated.value = true;
  showIconPicker.value = false;
  iconSearchQuery.value = "";

  showModal.value = true;
}

function openEditModal(module: Module): void {
  editingModule.value = module;

  form.value = {
    name: module.name,
    slug: module.slug,
    description: module.description ?? "",
    icon: module.icon ?? "",
    sort_order: Math.max(0, Number(module.sort_order) || 0),
    is_active: module.is_active,
  };

  validationErrors.value = {};
  operationMessage.value = "";

  slugWasAutoGenerated.value = false;
  showIconPicker.value = false;
  iconSearchQuery.value = "";

  showModal.value = true;
}

function resetForm(): void {
  form.value = createEmptyForm();
  validationErrors.value = {};
}

function closeModal(): void {
  if (isSaving.value) {
    return;
  }

  showModal.value = false;
  editingModule.value = null;

  showIconPicker.value = false;
  iconSearchQuery.value = "";

  resetForm();
}

function clearOperationMessage(): void {
  operationMessage.value = "";
}

function fieldError(field: string): string {
  return validationErrors.value[field]?.[0] ?? "";
}

/* -------------------------------------------------------------------------- */
/* Slug                                                                       */
/* -------------------------------------------------------------------------- */

function slugify(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function normalizeSlug(): void {
  form.value.slug = slugify(form.value.slug);
}

function generateSlugFromName(): void {
  if (isEditing.value) {
    return;
  }

  form.value.slug = slugify(form.value.name);
}

watch(
  () => form.value.name,
  () => {
    if (!isEditing.value && slugWasAutoGenerated.value) {
      generateSlugFromName();
    }
  },
);

/* -------------------------------------------------------------------------- */
/* Sort Order                                                                 */
/* -------------------------------------------------------------------------- */

const nextAvailableSortOrder = computed<number>(() => {
  if (modules.value.length === 0) {
    return 10;
  }

  const highest = modules.value.reduce((maximum, module) => {
    return Math.max(maximum, Number(module.sort_order) || 0);
  }, 0);

  return Math.max(10, highest + 10);
});

const sortOrderPosition = computed<number>(() => {
  const current = Math.max(0, Number(form.value.sort_order) || 0);

  const ordered = [...modules.value]
    .filter((module) => {
      if (editingModule.value === null) {
        return true;
      }

      return module.id !== editingModule.value.id;
    })
    .sort((a, b) => {
      const orderDifference =
        (Number(a.sort_order) || 0) - (Number(b.sort_order) || 0);

      if (orderDifference !== 0) {
        return orderDifference;
      }

      return a.name.localeCompare(b.name);
    });

  let position = 1;

  for (const module of ordered) {
    if ((Number(module.sort_order) || 0) <= current) {
      position += 1;
    }
  }

  return position;
});

const totalOrderSlots = computed<number>(() => {
  return Math.max(modules.value.length + (isEditing.value ? 0 : 1), 1);
});

function normalizeSortOrder(): void {
  const value = Number(form.value.sort_order);

  if (!Number.isFinite(value)) {
    form.value.sort_order = 0;
    return;
  }

  form.value.sort_order = Math.max(0, Math.min(9999, Math.floor(value)));
}

function increaseSortOrder(): void {
  form.value.sort_order = Math.min(
    9999,
    Math.max(0, Number(form.value.sort_order) || 0) + 1,
  );
}

function decreaseSortOrder(): void {
  form.value.sort_order = Math.max(
    0,
    (Number(form.value.sort_order) || 0) - 1,
  );
}

function setSortOrder(value: number): void {
  form.value.sort_order = Math.max(0, Math.min(9999, Math.floor(value)));
}

function applyAutoSortOrder(): void {
  form.value.sort_order = nextAvailableSortOrder.value;
}

/* -------------------------------------------------------------------------- */
/* Icon Picker                                                                 */
/* -------------------------------------------------------------------------- */

function selectIcon(icon: IconOption): void {
  form.value.icon = icon.name;
  showIconPicker.value = false;
  iconSearchQuery.value = "";
}

function clearSelectedIcon(): void {
  form.value.icon = "";
  showIconPicker.value = false;
  iconSearchQuery.value = "";
}

function toggleIconPicker(): void {
  if (isSaving.value || isSystemModule.value) {
    return;
  }

  showIconPicker.value = !showIconPicker.value;

  if (showIconPicker.value) {
    iconSearchQuery.value = "";
  }
}

function closeIconPicker(): void {
  showIconPicker.value = false;
}

function handleDocumentPointerDown(event: MouseEvent): void {
  const target = event.target;

  if (!(target instanceof HTMLElement)) {
    return;
  }

  if (!target.closest(".icon-picker")) {
    closeIconPicker();
  }
}

function handleDocumentKeydown(event: KeyboardEvent): void {
  if (event.key === "Escape") {
    if (showIconPicker.value) {
      closeIconPicker();
      return;
    }

    if (showModal.value && !isSaving.value) {
      closeModal();
    }
  }
}

/* -------------------------------------------------------------------------- */
/* CSRF                                                                       */
/* -------------------------------------------------------------------------- */

function getCsrfToken(): string | null {
  const cookie = document.cookie
    .split("; ")
    .find((row) => row.startsWith("XSRF-TOKEN="));

  if (!cookie) {
    return null;
  }

  const value = cookie.substring("XSRF-TOKEN=".length);

  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

function buildHeaders(): Record<string, string> {
  const headers: Record<string, string> = {
    Accept: "application/json",
    "Content-Type": "application/json",
    "X-Requested-With": "XMLHttpRequest",
  };

  const csrfToken = getCsrfToken();

  if (csrfToken) {
    headers["X-XSRF-TOKEN"] = csrfToken;
  }

  return headers;
}

/* -------------------------------------------------------------------------- */
/* JSON response handling                                                     */
/* -------------------------------------------------------------------------- */

async function readJsonResponse<T>(
  response: Response,
): Promise<ApiResponse<T>> {
  const text = await response.text();

  if (!text.trim()) {
    return {};
  }

  try {
    return JSON.parse(text) as ApiResponse<T>;
  } catch {
    const contentType = response.headers.get("content-type") ?? "";

    if (contentType.includes("text/html")) {
      throw new Error(
        response.ok
          ? "The server returned an unexpected HTML response."
          : `Server returned HTTP ${response.status}.`,
      );
    }

    throw new Error(
      response.ok
        ? "The server returned an invalid JSON response."
        : `Request failed with HTTP ${response.status}.`,
    );
  }
}

function getApiErrorMessage(
  payload: ApiErrorResponse | ApiResponse<unknown>,
  fallback: string,
): string {
  if (payload.message) {
    return payload.message;
  }

  return fallback;
}

/* -------------------------------------------------------------------------- */
/* API                                                                        */
/* -------------------------------------------------------------------------- */

async function fetchModules(): Promise<void> {
  isLoading.value = true;
  clearOperationMessage();

  try {
    const response = await fetch("/api/modules", {
      method: "GET",
      headers: {
        Accept: "application/json",
        "X-Requested-With": "XMLHttpRequest",
      },
      credentials: "same-origin",
    });

    const payload = await readJsonResponse<Module[]>(response);

    if (!response.ok) {
      throw new Error(
        getApiErrorMessage(
          payload,
          `Unable to load modules. HTTP ${response.status}.`,
        ),
      );
    }

    modules.value = Array.isArray(payload.data) ? payload.data : [];
  } catch (error) {
    operationMessageType.value = "error";

    operationMessage.value =
      error instanceof Error ? error.message : "Unable to load modules.";
  } finally {
    isLoading.value = false;
  }
}

async function saveModule(): Promise<void> {
  validationErrors.value = {};
  clearOperationMessage();

  const name = form.value.name.trim();
  const slug = form.value.slug.trim();

  if (!name) {
    validationErrors.value.name = ["The name field is required."];
  }

  if (!slug) {
    validationErrors.value.slug = ["The slug field is required."];
  }

  if (
    slug &&
    !/^[a-z0-9]+(?:[._-][a-z0-9]+)*$/.test(slug)
  ) {
    validationErrors.value.slug = [
      "Use lowercase letters, numbers, dots, underscores, or hyphens.",
    ];
  }

  if (Object.keys(validationErrors.value).length > 0) {
    return;
  }

  if (isSystemModule.value) {
    operationMessageType.value = "error";
    operationMessage.value =
      "System modules are protected and cannot be modified.";
    return;
  }

  normalizeSortOrder();

  isSaving.value = true;

  try {
    const editing = editingModule.value !== null;

    const endpoint = editing
      ? `/api/modules/${editingModule.value!.id}`
      : "/api/modules";

    const method = editing ? "PUT" : "POST";

    const response = await fetch(endpoint, {
      method,
      headers: buildHeaders(),
      credentials: "same-origin",
      body: JSON.stringify({
        name,
        slug,
        description: form.value.description.trim() || null,
        icon: form.value.icon.trim() || null,
        sort_order: Number(form.value.sort_order) || 0,
        is_active: Boolean(form.value.is_active),
      }),
    });

    const payload = await readJsonResponse<Module>(response);

    if (!response.ok) {
      if (payload.errors) {
        const normalizedErrors: Record<string, string[]> = {};

        for (const [field, messages] of Object.entries(
          payload.errors,
        )) {
          normalizedErrors[field] = Array.isArray(messages)
            ? messages
            : [messages];
        }

        validationErrors.value = normalizedErrors;
      }

      throw new Error(
        getApiErrorMessage(
          payload,
          editing
            ? "Unable to update module."
            : "Unable to create module.",
        ),
      );
    }

    const successMessage = editing
      ? "Module updated successfully."
      : "Module created successfully.";

    operationMessageType.value = "success";
    operationMessage.value = successMessage;

    showModal.value = false;
    editingModule.value = null;
    showIconPicker.value = false;
    iconSearchQuery.value = "";

    resetForm();

    await fetchModules();

    operationMessageType.value = "success";
    operationMessage.value = successMessage;
  } catch (error) {
    operationMessageType.value = "error";

    operationMessage.value =
      error instanceof Error
        ? error.message
        : "Unable to save module.";
  } finally {
    isSaving.value = false;
  }
}

