<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\MorphTo;
use Illuminate\Support\Carbon;

/**
 * Immutable application activity/audit record.
 *
 * @property int $id
 * @property int|null $actor_user_id
 * @property string $actor_type
 * @property string $action
 * @property string $module
 * @property string $description
 * @property string|null $subject_type
 * @property int|string|null $subject_id
 * @property array<string, mixed>|null $old_values
 * @property array<string, mixed>|null $new_values
 * @property string|null $ip_address
 * @property string|null $user_agent
 * @property string|null $request_id
 * @property array<string, mixed>|null $metadata
 * @property Carbon $created_at
 * @property-read User|null $actor
 * @property-read Model|null $subject
 * @property-read string $actor_display_name
 */
#[Fillable([
    'actor_user_id',
    'actor_type',
    'action',
    'module',
    'description',
    'subject_type',
    'subject_id',
    'old_values',
    'new_values',
    'ip_address',
    'user_agent',
    'request_id',
    'metadata',
    'created_at',
])]
class ActivityLog extends Model
{
    /**
     * Activity logs are immutable records.
     *
     * The table intentionally has no updated_at column.
     */
    public $timestamps = false;

    /**
     * Get the user responsible for the activity.
     *
     * For Developer actions this relationship still points to the actual
     * Developer account even though the displayed actor is "System".
     *
     * @return BelongsTo<User, $this>
     */
    public function actor(): BelongsTo
    {
        return $this->belongsTo(
            User::class,
            'actor_user_id',
        );
    }

    /**
     * Get the model affected by this activity.
     *
     * @return MorphTo<Model, $this>
     */
    public function subject(): MorphTo
    {
        return $this->morphTo();
    }

    /**
     * Get the presentation label for the actor.
     *
     * Developer actions are intentionally presented as "System".
     *
     * The actual actor_user_id remains stored for internal traceability.
     */
    public function getActorDisplayNameAttribute(): string
    {
        if ($this->actor_type === 'system') {
            return 'System';
        }

        return $this->actor?->name ?? 'Unknown User';
    }

    /**
     * Determine whether this activity was generated by the system.
     */
    public function isSystemActivity(): bool
    {
        return $this->actor_type === 'system';
    }

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'old_values' => 'array',
            'new_values' => 'array',
            'metadata' => 'array',
            'created_at' => 'datetime',
        ];
    }
}
